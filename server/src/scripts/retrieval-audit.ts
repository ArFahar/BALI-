/**
 * Read-only RAG audit (TASK 01): knowledge coverage, index consistency, baseline top-10 retrieval,
 * what the relevance gate and context builder keep, and what the LLM did with it.
 *
 *   npm run audit:retrieval --workspace server          (needs DATABASE_URL -> pgvector)
 *
 * Writes docs/eval/RETRIEVAL_AUDIT_RAG-001.md. Retrieval parameters are NOT changed: this is the baseline.
 */
import fs from 'node:fs';
import path from 'node:path';
import { bootstrap } from '../bootstrap.js';
import { config, REPO_ROOT } from '../config.js';
import { getPool } from '../db/pool.js';
import { SCOPES_FOR_CANGGU } from '../kb/store.js';
import { RagPipeline } from '../rag/pipeline.js';
import type { Language, ScoredChunk } from '../types.js';

const QUERIES: { text: string; language: Language }[] = [
  { text: 'Apakah saya boleh makan babi di upacara adat?', language: 'id' },
  { text: 'Apakah daging babi diperbolehkan dalam ritual adat Bali?', language: 'id' },
  { text: 'What food restrictions apply during Balinese traditional ceremonies?', language: 'en' },
];
// Diagnostic keyword search only (not the retrieval mechanism). \m = word start in PostgreSQL regex.
const FOOD_TERMS = ['babi', 'daging', 'makan', 'makanan', 'konsumsi', 'hidangan', 'pantangan', 'pork', 'food', 'eat', 'eating', 'meat'];
const TOP_K = 10;

const cell = (s: unknown) => String(s ?? '—').replace(/\|/g, '/').replace(/\s+/g, ' ').trim();
const body = (content: string) => content.split('\n').slice(1).join(' ');
const snip = (s: string, n = 180) => (s.length > n ? `${s.slice(0, n)}…` : s);

if (config.kbSource !== 'pgvector') throw new Error('Set DATABASE_URL (pgvector / Supabase) to audit the deployed index.');

const deps = await bootstrap();
const pool = getPool();
const out: string[] = [];
const traces: Record<string, unknown>[] = [];
const pipeline = new RagPipeline({
  store: deps.store,
  embedder: deps.embedder,
  translator: deps.translator,
  llm: deps.llm,
  topK: config.retrievalTopK,
  minScore: config.retrievalMinScore,
  strongScore: config.retrievalStrongScore,
  standaloneScore: config.retrievalStandaloneScore,
  logger: console,
  trace: (stage, data) => traces.push({ stage, ...data }),
});

out.push(`# Retrieval audit RAG-001 (generated)

Generated by \`npm run audit:retrieval\` on ${new Date().toISOString()}. Read-only; retrieval parameters unchanged (baseline).

- Knowledge base: \`${deps.store.kind}\` (Supabase) · embedder (B): \`${deps.embedder.id}\` · query translation: \`${deps.translator?.id ?? 'off'}\` · LLM: \`${deps.llm?.id ?? 'none'}\`
- Gate: score ≥ ${config.retrievalMinScore} AND (category detected by classifier OR score ≥ ${config.retrievalStandaloneScore}); context = up to 3 chunks within 0.03 of the best; search filter: scope ∈ {${SCOPES_FOR_CANGGU.join(', ')}}, status ≠ EXPIRED.
`);

// ---------------------------------------------------------------- 1. Knowledge coverage
out.push('## 1. Knowledge coverage (keyword diagnostic, all 120 chunks)\n');
const { rows: total } = await pool.query('SELECT count(*)::int AS n FROM knowledge_chunks');
const { rows: upacara } = await pool.query(`SELECT count(*)::int AS n FROM knowledge_chunks WHERE content ~* '\\mupacara'`);
out.push(`Chunks: ${total[0].n}. Chunks mentioning "upacara": ${upacara[0].n}.\n`);
out.push('| term | chunks | chunk ids |\n|---|---|---|');
const foodHits = new Map<string, string>();
for (const term of FOOD_TERMS) {
  const { rows } = await pool.query(`SELECT chunk_key, content FROM knowledge_chunks WHERE content ~* $1 ORDER BY chunk_key`, [`\\m${term}\\M`]);
  for (const r of rows) {
    const m = new RegExp(`.{0,90}\\b${term}\\b.{0,90}`, 'is').exec(body(r.content));
    if (!foodHits.has(r.chunk_key) && m) foodHits.set(r.chunk_key, `[${term}] ${m[0]}`);
  }
  out.push(`| ${term} | ${rows.length} | ${rows.map((r) => r.chunk_key).join(', ') || '—'} |`);
}
out.push('\nContext around each keyword hit (to judge whether it is about eating at ceremonies):\n');
out.push('| chunk | excerpt |\n|---|---|');
for (const [k, v] of foodHits) out.push(`| ${k} | ${cell(v)} |`);

// ---------------------------------------------------------------- 2. Index consistency
const { rows: idx } = await pool.query(
  `SELECT count(*)::int AS total, count(embedding)::int AS embedded, array_agg(DISTINCT embedding_model) AS models,
          array_agg(DISTINCT vector_dims(embedding)) AS dims FROM knowledge_chunks`,
);
out.push(`\n## 2. Index consistency\n
| total chunks | with embedding | embedding models | dimensions | query model |
|---|---|---|---|---|
| ${idx[0].total} | ${idx[0].embedded} | ${idx[0].models.join(', ')} | ${idx[0].dims.join(', ')} | ${deps.embedder.id} |
`);

// ---------------------------------------------------------------- 3-5. Retrieval, gate, context, generation
const filter = { scopes: SCOPES_FOR_CANGGU, excludeStatuses: ['EXPIRED' as const] };
const row = (i: number, h: { chunk: ScoredChunk['chunk']; score: number }, kept: Set<string>) =>
  `| ${i + 1} | ${h.chunk.chunk_key} | ${h.score.toFixed(3)} | ${h.chunk.category} | ${h.chunk.location_scope} | ${h.chunk.source_type}/${h.chunk.source_subtype ?? '—'} | ${h.chunk.validation_status} | ${kept.has(h.chunk.chunk_key) ? '✅' : ''} | ${cell(snip(body(h.chunk.content)))} |`;
const header = '| rank | chunk id (C) | score (E) | category (F) | location (G) | source type | status (H) | in context | content (D) |\n|---|---|---|---|---|---|---|---|---|';

for (const [qi, q] of QUERIES.entries()) {
  traces.length = 0;
  const res = await pipeline.handle({ message: q.text, language: q.language, user_type: 'tourist', location: 'canggu' });
  const tr = traces.find((t) => t.stage === 'retrieval') as
    | { translation: string | null; expanded: string; detected_categories: string[]; context: ScoredChunk[] }
    | undefined;
  const gen = traces.find((t) => t.stage === 'generation') as
    | { used_source_ids?: string[]; answer?: string; uncertainty_note?: string | null; user_prompt?: string }
    | undefined;
  const kept = new Set((tr?.context ?? []).map((c) => c.chunk.chunk_key));

  out.push(`\n## 3.${qi + 1} Query (A): "${q.text}" (${q.language}, tourist)\n`);
  out.push(`- Translation used for retrieval: ${tr?.translation ? `"${tr.translation}"` : '—'}`);
  out.push(`- Expanded variant (translation + glossary): "${tr?.expanded ?? ''}"`);
  out.push(`- Categories detected by the keyword classifier: ${tr?.detected_categories.join(', ') || 'none'}\n`);

  const variants: [string, string][] = [['original query', q.text]];
  if (tr?.expanded) variants.push(['translated / expanded variant', tr.expanded]);
  for (const [label, text] of variants) {
    const hits = await deps.store.search(await deps.embedder.embedQuery(text), filter, TOP_K);
    out.push(`**Top ${TOP_K} — ${label}**\n\n${header}`);
    hits.forEach((h, i) => out.push(row(i, h, kept)));
    out.push('');
  }

  // Where do the keyword hits rank semantically?
  const all = await deps.store.search(await deps.embedder.embedQuery(q.text), filter, 200);
  const ranks = [...foodHits.keys()].map((k) => `${k} → #${all.findIndex((h) => h.chunk.chunk_key === k) + 1}`);
  out.push(`Semantic rank (original query) of the keyword-hit chunks: ${ranks.join('; ') || '—'}\n`);

  out.push(`**Final context sent to the LLM (after gate):** ${[...kept].join(', ') || '(none — no LLM call)'}\n`);
  if (gen) {
    out.push(`**LLM:** used_source_ids = ${JSON.stringify(gen.used_source_ids ?? [])}; draft answer: "${cell(snip(gen.answer ?? '', 400))}"${gen.uncertainty_note ? `; uncertainty_note: "${cell(gen.uncertainty_note)}"` : ''}\n`);
  }
  out.push(`**Final response:** status \`${res.retrieval_status}\`, mode \`${res.generation_mode}\`, sources ${res.sources.map((s) => s.id).join(', ') || '—'}\n\n> ${cell(snip(res.answer, 500))}\n`);
}

const file = path.join(REPO_ROOT, 'docs', 'eval', 'RETRIEVAL_AUDIT_RAG-001.md');
fs.writeFileSync(file, out.join('\n') + '\n');
console.log(`wrote ${path.relative(REPO_ROOT, file)}`);
process.exit(0);
