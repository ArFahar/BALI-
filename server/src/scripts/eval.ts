/**
 * Runs the evaluation scenarios against the real pipeline (real embeddings, configured LLM or extractive mode)
 * and writes a Markdown + JSON report to docs/eval/. Numbers in the report are measured, not estimated.
 */
import fs from 'node:fs';
import path from 'node:path';
import { REPO_ROOT } from '../config.js';
import { bootstrap } from '../bootstrap.js';
import { closePool } from '../db/pool.js';
import { detectLanguage } from '../rag/classifier.js';
import { EVAL_SCENARIOS } from '../eval/scenarios.js';
import type { ChatResponse } from '../types.js';

interface Row {
  id: string;
  kind: string;
  message: string;
  language: string;
  status: string;
  expectedStatus: string;
  topSources: string;
  topScore: number | null;
  statusOk: boolean;
  citationOk: boolean;
  grounded: boolean;
  languageOk: boolean;
  caveatOk: boolean;
  mode: string;
  pass: boolean;
}

const pct = (n: number, d: number) => (d ? `${((n / d) * 100).toFixed(1)}% (${n}/${d})` : 'n/a');

async function main() {
  const { pipeline, embedder, llm, store, translator } = await bootstrap();
  const rows: Row[] = [];
  const raw: Record<string, ChatResponse> = {};

  for (const s of EVAL_SCENARIOS) {
    const res = await pipeline.handle({ message: s.message, language: s.language, user_type: s.user_type, location: 'canggu' });
    raw[s.id] = res;
    const srcIds = res.sources.map((x) => x.id);
    const shouldAnswer = s.expectSources.length > 0;
    const statusOk = s.expectStatus.includes(res.retrieval_status);
    // Chunk keys are matched by prefix ("CANGGU-AWIG-2012-ID::Pasal-4" accepts "...::Pasal-4#1").
    const citationOk = shouldAnswer ? srcIds.length > 0 && s.expectSources.some((p) => srcIds[0].startsWith(p)) : srcIds.length === 0 || !res.fallback_used;
    const grounded = res.fallback_used ? res.sources.length === 0 : res.sources.length > 0;
    const textLang = detectLanguage(`${res.answer} ${res.why_it_matters ?? ''}`);
    const languageOk = textLang === null || textLang === s.language;
    const caveatOk = s.expectCaveat ? s.expectCaveat.test([res.answer, ...res.caveats].join(' ')) : true;
    rows.push({
      id: s.id,
      kind: s.kind,
      message: s.message,
      language: s.language,
      status: res.retrieval_status,
      expectedStatus: s.expectStatus.join('|'),
      topSources: srcIds.join(', ') || '—',
      topScore: res.sources[0]?.relevance ?? null,
      statusOk,
      citationOk,
      grounded,
      languageOk,
      caveatOk,
      mode: res.generation_mode,
      pass: statusOk && citationOk && grounded && languageOk && caveatOk,
    });
  }

  const scenarioOf = (r: Row) => EVAL_SCENARIOS.find((s) => s.id === r.id)!;
  const metricsFor = (rows: Row[]) => {
  const answerable = rows.filter((r) => scenarioOf(r).expectSources.length > 0);
  const fallbackCases = rows.filter((r) => scenarioOf(r).expectSources.length === 0);
  return {
    scenarios: rows.length,
    passed: rows.filter((r) => r.pass).length,
    retrieval_relevance_top1: pct(answerable.filter((r) => r.citationOk).length, answerable.length),
    citation_correctness: pct(answerable.filter((r) => r.citationOk && r.grounded).length, answerable.length),
    grounded_response_rate: pct(rows.filter((r) => r.grounded).length, rows.length),
    fallback_correctness: pct(fallbackCases.filter((r) => r.statusOk).length, fallbackCases.length),
    language_consistency: pct(rows.filter((r) => r.languageOk).length, rows.length),
    caveat_correctness: pct(rows.filter((r) => r.caveatOk).length, rows.length),
  };
  };
  const tuning = rows.filter((r) => scenarioOf(r).split === "tuning");
  const holdout = rows.filter((r) => scenarioOf(r).split === "holdout");
  const splits = { all: metricsFor(rows), tuning: metricsFor(tuning), holdout: metricsFor(holdout) };
  const metrics = splits.all;

  const env = { embedder: embedder.id, llm: llm?.id ?? 'none (extractive mode)', store: store.kind, translator: translator?.id ?? 'off', run_at: new Date().toISOString() };
  const outDir = path.join(REPO_ROOT, 'docs', 'eval');
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(path.join(outDir, 'eval-results.json'), JSON.stringify({ env, metrics: splits, rows, responses: raw }, null, 2));

  const yes = (b: boolean) => (b ? '✅' : '❌');
  const md = [
    '# Evaluation report (generated)',
    '',
    `Generated by \`npm run eval\` on ${env.run_at}.`,
    '',
    `- Embedder: \`${env.embedder}\``,
    `- LLM: \`${env.llm}\``,
    `- Knowledge base: \`${env.store}\``,
    `- Query translation: \`${env.translator}\``,
    '',
    '## Metrics',
    '',
    'Knowledge base v2 (Database/ sources). *holdout* = scenarios written before running v2 on them, with retrieval thresholds inherited from v1 and not adjusted for this set. *tuning* = scenarios added or changed after looking at results (empty if none).',
    '',
    '| Metric | All | Tuning | Holdout |',
    '|---|---|---|---|',
    ...(Object.keys(metrics) as (keyof typeof metrics)[]).map(
      (k) => `| ${k} | ${splits.all[k]} | ${splits.tuning[k]} | ${splits.holdout[k]} |`,
    ),
    '',
    '## Scenarios',
    '',
    '| ID | Kind | Lang | Question | Status (expected) | Sources | Top score | Status | Citation | Grounded | Lang | Caveat | Pass |',
    '|---|---|---|---|---|---|---|---|---|---|---|---|---|',
    ...rows.map(
      (r) =>
        `| ${r.id} | ${r.kind} | ${r.language} | ${r.message.replace(/\|/g, '/')} | ${r.status} (${r.expectedStatus}) | ${r.topSources} | ${r.topScore ?? '—'} | ${yes(r.statusOk)} | ${yes(r.citationOk)} | ${yes(r.grounded)} | ${yes(r.languageOk)} | ${yes(r.caveatOk)} | ${yes(r.pass)} |`,
    ),
    '',
  ].join('\n');
  fs.writeFileSync(path.join(outDir, 'EVAL_REPORT.md'), md);

  console.log(md);
  await closePool();
}

main().catch(async (err) => {
  console.error(err);
  await closePool();
  process.exit(1);
});
